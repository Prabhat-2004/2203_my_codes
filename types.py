#(1)__FUNCTION WITHOUT PARAMETER AND WITHOUT RETURN VALUE__!!
def add():
    a = 10
    b = 20
    c = 30
    print(a+b+c, end="\n\n")
add()

#(2)__FUNCTION WITHOUT PARAMETER AND WITH RETURN VALUE__!!
def greet():
    a = 120
    b =213
    return a + b
r = greet()
print(r,end="\n\n")


#(3)__FUNCTION WITH PARAMETER AND WITHOUT RETURN VALUE__!!
def pree(a,b,c,d):
    print(a+b+c+d,end="\n\n")
pree(22,10,3,12)


#(4)__FUNCTION WITH PARAMETRE AND WITH RETURN VALUE__!!
def pre(a,b,c):
    return a+b+c
res = pre(11,22,33)
print(res)
    