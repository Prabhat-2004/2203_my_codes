# (1) Arithmetric Operator
a = 13
b = 4
print(a+b)
print(a-b)
print(a*b)
print(a/b)
print(a//b)
print(a**b)

# (2) Relational Operator
c = 4
d = 5
print(c<d)
print(c>d)
print(c<=d)
print(c>=d)
print(c==d)
print(c!=d)

# (3) Logical Operator
e = 22
f = 33
print(e<f and e>f)
print(e<f or e>f)
print(not(e<f and e>f))

# (4) BitWise Operator
print(5 & 6)
print(5 | 6)
print(5 ^ 6)
print(~(5 ^ 6))
